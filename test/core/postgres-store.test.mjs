import test from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { createPostgresStore } from '../../src/core/postgres-store.mjs';
import { createCostLedger } from '../../src/runs/cost-ledger.mjs';
import { createPublicAuditWorkflow } from '../../src/audit/public-audit-workflow.mjs';
import { readFile } from 'node:fs/promises';
import { createPublicControlPlane } from '../../src/public/public-control-plane.mjs';

test('PostgreSQL conserve les résultats et sérialise écritures et budgets entre instances', { skip: !process.env.ANCRAGE_TEST_DATABASE_URL }, async () => {
  const { Pool } = await import('pg');
  const pool = new Pool({ connectionString: process.env.ANCRAGE_TEST_DATABASE_URL, max: 4, connectionTimeoutMillis: 10000 });
  const namespace = `test-${randomUUID()}`;
  const first = createPostgresStore({ pool, namespace });
  const second = createPostgresStore({ pool, namespace });
  try {
    await Promise.all([first.ready, second.ready]);
    const saved = await first.writeJson('reports/result.json', { status: 'PARTIAL' }, { expectedHash: null });
    assert.deepEqual(await second.readJson('reports/result.json'), { status: 'PARTIAL' });
    const writes = await Promise.allSettled([first, second].map(store => store.writeText('reports/result.json', 'next', { expectedHash: saved.hash })));
    assert.equal(writes.filter(value => value.status === 'fulfilled').length, 1);
    assert.equal(writes.find(value => value.status === 'rejected').reason.code, 'CONFLICT');
    const pdf = Buffer.from([0, 255, 128, 10]);
    await first.writeBuffer('reports/report.pdf', pdf, { immutable: true });
    assert.deepEqual(await second.readBuffer('reports/report.pdf'), pdf);
    await assert.rejects(() => second.writeBuffer('reports/report.pdf', pdf, { immutable: true }), { code: 'CONFLICT' });
    await Promise.all([first.appendJsonLine('events/log.jsonl', { id: 1 }), second.appendJsonLine('events/log.jsonl', { id: 2 })]);
    assert.equal((await first.readText('events/log.jsonl')).trim().split('\n').length, 2);
    await assert.rejects(() => first.withLock('transaction/test', async () => { await first.writeText('rollback/value', 'discard'); throw new Error('rollback'); }));
    assert.equal(await second.readText('rollback/value'), null);
    const ledgers = [first, second].map(store => createCostLedger({ store, runId: 'hosted-test', envelope: { hardLimit: 1 } }));
    await Promise.all(ledgers.map(ledger => ledger.ready));
    const reservations = await Promise.allSettled(ledgers.map(ledger => ledger.authorize({ stepId: 'analysis', provider: 'test', unit: 'call', estimatedCost: 0.75 })));
    assert.equal(reservations.filter(value => value.status === 'fulfilled').length, 1);
    assert.equal(reservations.find(value => value.status === 'rejected').reason.code, 'BUDGET_EXCEEDED');
    const restarted = createCostLedger({ store: second, runId: 'hosted-test', envelope: { hardLimit: 1 } });
    await restarted.ready;
    assert.equal(restarted.snapshot().reserved, 0.75);
    const leaseKey = 'jobs/test.lease';
    const acquired = await Promise.all([first.acquireLease(leaseKey, 'worker-a', 60000), second.acquireLease(leaseKey, 'worker-b', 60000)]);
    assert.equal(acquired.filter(Boolean).length, 1);
    const owner = acquired.find(Boolean).token;
    assert.equal((await second.leaseState(leaseKey)).state, 'ACTIVE');
    assert.equal(await second.renewLease(leaseKey, 'other-worker', 60000), false);
    assert.equal(await second.releaseLease(leaseKey, 'other-worker'), false);
    assert.equal(await second.renewLease(leaseKey, owner, 60000), true);
    await first.writeJson(leaseKey, { token: owner, expiresAt: '2000-01-01T00:00:00.000Z' });
    assert.equal((await second.leaseState(leaseKey)).state, 'EXPIRED');
    assert.equal(await second.renewLease(leaseKey, owner, 60000), false);
    assert.equal(await second.recoverExpiredLease(leaseKey, 'other-worker'), 'ACTIVE');
    assert.equal(await second.recoverExpiredLease(leaseKey, owner), 'RECOVERED');
    assert.equal((await first.leaseState(leaseKey)).state, 'MISSING');
    assert.ok(await first.acquireLease(leaseKey, 'new-worker', 60000));
    assert.equal(await first.releaseLease(leaseKey, owner), false);
    assert.equal(await first.releaseLease(leaseKey, 'new-worker'), true);
    let entered; const active = new Promise(resolve => { entered = resolve; });
    let continueWorker; const hold = new Promise(resolve => { continueWorker = resolve; });
    const workerKey = 'jobs/fenced.lease';
    const worker = first.withLease(workerKey, async () => {
      await first.writeText('jobs/owned-output', 'initial');
      entered();
      await hold;
      await assert.rejects(() => first.writeText('jobs/owned-output', 'stale'), { code: 'CONFLICT' });
    });
    await active;
    await assert.rejects(() => second.withLease(workerKey, async () => {}), { code: 'CONFLICT' });
    await second.writeJson(workerKey, { token: 'replacement-worker', expiresAt: '2099-01-01T00:00:00.000Z' });
    continueWorker();
    await worker;
    assert.equal(await second.readText('jobs/owned-output'), 'initial');
    assert.equal((await second.leaseState(workerKey)).metadata.token, 'replacement-worker');
    const schema = JSON.parse(await readFile(new URL('../../fixtures/defaults/contracts/audit-packet.schema.json', import.meta.url), 'utf8'));
    const contracts = { getActiveVersion: async () => ({ schema, versionId: 'fixture-v1' }) };
    const workflows = [first, second].map(store => createPublicAuditWorkflow({ store, contracts }));
    const input = { name: 'Fixture hébergée', city: { id: 'fr-nantes', label: 'Nantes', country: 'FR' }, identity: { source: 'google-places', placeId: 'fixture-only' }, idempotencyKey: 'concurrent-hosted-creation' };
    const created = await Promise.all(workflows.map(workflow => workflow.create(input, { defer: true })));
    assert.equal(created[0].id, created[1].id);
    assert.equal((await workflows[0].list()).length, 1);
    assert.equal(created[0].status, 'RUNNING');
    const resumed = await Promise.allSettled(workflows.map(workflow => workflow.resume(created[0].id)));
    assert.equal(resumed.filter(item => item.status === 'fulfilled').length, 1);
    assert.equal(resumed.find(item => item.status === 'rejected').reason.code, 'CONFLICT');
    const finished = await workflows[1].get(created[0].id);
    assert.equal(finished.status, 'PARTIAL');
    assert.equal(finished.reports.filter(item => item.kind === 'final').length, 1);
    assert.match((await workflows[1].readReport(finished.id, 'final', 'pdf')).value, /^%PDF/);
    assert.equal((await workflows[1].resume(finished.id)).id, finished.id);
    const queued = await workflows[0].create({ ...input, idempotencyKey: 'scheduled-hosted-audit' }, { defer: true });
    assert.deepEqual(await workflows[1].workPending(), [{ id: queued.id, status: 'PARTIAL' }]);
    assert.deepEqual(await workflows[0].workPending(), []);
    const planes = workflows.map((workflow, index) => createPublicControlPlane({ store: index ? second : first, auditStarter: async ({ request, decision }) => {
      const audit = await workflow.create({ ...input, idempotencyKey: `public-${request.id}` }, { defer: true, mode: decision });
      const reports = { audit: { id: audit.id, status: audit.status }, deferred: audit.status === 'RUNNING' };
      for (const kind of ['gmb', 'final']) if (audit.reports.some(item => item.kind === kind)) reports[kind] = { html: (await workflow.readReport(audit.id, kind)).value, ...(kind === 'final' ? { pdf: (await workflow.readReport(audit.id, kind, 'pdf')).value } : {}) };
      return reports;
    } }));
    const publicInput = { name: input.name, city: { ...input.city, countryCode: 'FR' }, identity: { ...input.identity, address: 'Fixture, Nantes' }, idempotencyKey: 'public-hosted' };
    const requests = await Promise.all(planes.map(plane => plane.createRequest(publicInput)));
    assert.equal(requests[0].id, requests[1].id);
    const accepted = await planes[0].decideMatch(requests[0].id, { decision: 'CONFIRM' });
    assert.equal(accepted.status, 'RUNNING');
    assert.equal(accepted.nextAction.kind, 'WAIT');
    await workflows[1].workPending();
    const refreshed = await planes[1].refreshAudit(accepted.id);
    assert.equal(refreshed.state, 'FINAL_REPORT_READY');
    assert.equal(refreshed.status, 'PARTIAL');
    assert.equal(refreshed.reports.length, 2);
    assert.equal((await planes[0].refreshAudit(accepted.id)).reports.length, 2);
    const publicPdf = refreshed.reports.find(report => report.kind === 'final');
    assert.match((await planes[0].readReport(accepted.id, publicPdf.id, 'pdf')).value, /^%PDF/);
    for (const key of ['../secret', '/absolute', 'a\\b', 'a//b']) await assert.rejects(() => first.readText(key), { code: 'PATH_VIOLATION' });
  } finally {
    await pool.query('DELETE FROM ancrage_objects WHERE namespace = $1', [namespace]);
    await pool.end();
  }
});
